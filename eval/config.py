"""
Evaluation configuration: thresholds, paths, and LLM judge settings.

All threshold values represent the *minimum acceptable* score for CI to pass.
They are deliberately conservative given the system has no re-ranking.
"""

from __future__ import annotations

from pathlib import Path

# ---------------------------------------------------------------------------
# Paths
# ---------------------------------------------------------------------------

EVAL_DIR = Path(__file__).parent
DATASET_DIR = EVAL_DIR / "dataset"
REPORTS_DIR = EVAL_DIR / "reports"

EVAL_DATASET_PATH = DATASET_DIR / "eval_dataset.json"
ADVERSARIAL_DATASET_PATH = DATASET_DIR / "adversarial_cases.json"

# ---------------------------------------------------------------------------
# Dataset generation settings
# ---------------------------------------------------------------------------

# Number of QA pairs to generate with RAGAS TestsetGenerator.
# Increase for broader coverage; decrease for faster/cheaper generation.
TESTSET_SIZE: int = 20

# Distribution of question types generated by RAGAS.
# Keys match ragas.testset.synthesizers names; values are relative weights.
TESTSET_DISTRIBUTION: dict[str, float] = {
    "simple": 0.5,       # Single-hop, factual questions
    "multi_context": 0.25,  # Requires combining 2+ chunks
    "reasoning": 0.25,   # Requires inference over retrieved context
}

# ---------------------------------------------------------------------------
# RAGAS metric thresholds  (0.0 – 1.0 scale)
# ---------------------------------------------------------------------------
# CI test fails if any metric falls below its threshold.
# Raise these thresholds once re-ranking or hybrid search is added.

THRESHOLDS: dict[str, float] = {
    "faithfulness": 0.75,        # Hallucination guard — claims grounded in context
    "answer_relevancy": 0.70,    # Answer actually addresses the question
    "context_precision": 0.60,   # Retrieved chunks are relevant (no noise)
    "context_recall": 0.65,      # All relevant info was retrieved
    "answer_correctness": 0.65,  # Factual match to reference answer
}

# ---------------------------------------------------------------------------
# Retrieval metric thresholds (custom, LLM-free)
# ---------------------------------------------------------------------------

RETRIEVAL_THRESHOLDS: dict[str, float] = {
    "hit_rate_at_5": 0.75,   # ≥1 relevant chunk in top-5 for 75 % of queries
    "mrr": 0.60,             # Mean reciprocal rank across all queries
}

# ---------------------------------------------------------------------------
# LLM judge settings  (used by RAGAS evaluators)
# ---------------------------------------------------------------------------

# Model used as the LLM judge inside RAGAS.
# Reuses the existing ANTHROPIC_API_KEY — no additional credentials needed.
JUDGE_MODEL: str = "claude-sonnet-4-5"

# Max tokens the judge can output per scoring call.
JUDGE_MAX_TOKENS: int = 1024

# ---------------------------------------------------------------------------
# Pipeline runner settings
# ---------------------------------------------------------------------------

# Session ID used by the eval runner (isolated from production sessions).
EVAL_SESSION_ID: str = "eval-pipeline-runner"

# Top-k documents to retrieve during evaluation runs.
EVAL_TOP_K: int = 5

# Timeout (seconds) for a single agent invocation during evaluation.
AGENT_TIMEOUT_SECONDS: int = 120
